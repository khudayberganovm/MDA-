// Verifies signed download + ffprobe for the latest completed project of a dev user.
import fs from "node:fs";
import path from "node:path";
import { startApi } from "../src/api/server.js";
import { config } from "../src/config.js";
import { db } from "../src/db.js";
import { probe } from "../src/lib/ffprobe.js";
const uid = process.argv[2] ?? "900001";
const app = await startApi();
const base = `http://127.0.0.1:${config.PORT}`;
const A = { Authorization: `dev ${uid}` };
const list = await (await fetch(`${base}/api/projects`, { headers: A })).json();
const p = list.find((x: { status: string }) => x.status === "completed");
const r = await fetch(`${base}/api/projects/${p.id}/download-link`, { method: "POST", headers: A });
const { url } = await r.json();
const dl = await fetch(url.replace(config.PUBLIC_URL, base));
const out = path.resolve(`media/e2e-${p.id}.mp4`);
fs.writeFileSync(out, Buffer.from(await dl.arrayBuffer()));
console.log("✔ downloaded", dl.status, (fs.statSync(out).size / 1e6).toFixed(2), "MB");
const bad = await fetch(url.replace(config.PUBLIC_URL, base).replace(/sig=./, "sig=0"));
console.log(bad.status === 403 ? "✔ tampered link rejected" : `✘ tampered link status ${bad.status}`);
const pr = await probe(out);
console.log("ffprobe:", pr.duration.toFixed(2) + "s", pr.streams.map((s) => `${s.codec_type}:${s.codec_name}${s.width ? ` ${s.width}x${s.height}` : ""}`).join(", "));
console.log("file:", out);
await app.close(); await db.$disconnect(); process.exit(0);
